from collections.abc import AsyncIterator
from contextlib import AbstractAsyncContextManager
from pathlib import Path
from typing import Protocol

from remote_ios_agent.core.models import Capability, DeviceInfo


class Backend(Protocol):
    simulated: bool

    async def connect(self) -> DeviceInfo: ...
    async def disconnect(self) -> None: ...
    def capabilities(self) -> dict[str, Capability]: ...
    async def screenshot(self) -> bytes: ...
    def interaction(self) -> AbstractAsyncContextManager: ...
    async def touch(self, x: int, y: int, *, end: tuple[int, int] | None, duration: float) -> None: ...
    async def type_text(self, text: str) -> None: ...
    async def press(self, button: str) -> None: ...
    async def install(self, path: Path) -> dict: ...
    async def launch(self, bundle_id: str) -> dict: ...
    async def terminate(self, bundle_id: str) -> dict: ...
    def logs(self, bundle_id: str) -> AsyncIterator[str]: ...
